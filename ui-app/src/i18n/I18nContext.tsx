type I18nValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (text: string) => string;
  locale: string;
};

const fallbackValue: I18nValue = {
  language: "en",
  setLanguage: () => undefined,
  t: (text) => text,
  locale: "en-US",
};

const I18nContext = createContext<I18nValue>(fallbackValue);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved === "en" || saved === "lt" ? saved : "lt";
  });

  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    localStorage.setItem(STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (text) => language === "lt" ? (lt[text] ?? text) : text,
    locale: language === "lt" ? "lt-LT" : "en-US",
  }), [language, setLanguage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

// eslint-disable-next-line react-refresh/only-export-components -- idiomatic context hook lives with its provider; a full reload on i18n edits is acceptable
export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
